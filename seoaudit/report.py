"""HTML, JSON and CSV reports."""

from __future__ import annotations

import csv
import io
import json
from html import escape
from pathlib import Path

from .audit import AuditResult
from .checks import score

SEV_COLOR = {"error": "#d93025", "warning": "#e37400", "notice": "#1a73e8"}


def _score_color(s: int) -> str:
    return "#188038" if s >= 80 else "#e37400" if s >= 50 else "#d93025"


def to_html(r: AuditResult) -> str:
    c = r.counts()
    ring = f"conic-gradient({_score_color(r.score)} {r.score * 3.6}deg, #e8eaed 0)"
    page_rows = []
    for p in r.pages:
        ps = score(r.issues_for(p.url), 1)
        page_rows.append(
            f'<tr><td><a href="{escape(p.url)}">{escape(p.url)}</a></td><td>{p.status or "-"}</td>'
            f"<td>{escape(p.title) or '<em>missing</em>'}</td><td>{p.word_count}</td><td>{p.load_ms} ms</td>"
            f'<td><b style="color:{_score_color(ps)}">{ps}</b></td></tr>'
        )
    issue_rows = "".join(
        f'<tr><td><span class="b" style="background:{SEV_COLOR[i.severity]}">{i.severity}</span></td>'
        f'<td class="u">{escape(i.url)}</td><td>{escape(i.message)}</td><td>{escape(i.fix)}</td></tr>'
        for i in r.issues
    ) or '<tr><td colspan="4">No issues found 🎉</td></tr>'
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>SEO audit: {escape(r.start_url)}</title>
<style>
body{{margin:0;font-family:Inter,system-ui,Segoe UI,Roboto,sans-serif;background:#f6f8fb;color:#1f2937}}
header{{background:linear-gradient(120deg,#065f46,#047857);color:#fff;padding:28px 40px;display:flex;gap:28px;align-items:center}}
.ring{{width:96px;height:96px;border-radius:50%;background:{ring};display:flex;align-items:center;justify-content:center}}
.ring span{{background:#fff;color:#111;width:74px;height:74px;border-radius:50%;display:flex;align-items:center;justify-content:center;font-size:28px;font-weight:800}}
h1{{margin:0;font-size:24px}} header p{{margin:6px 0 0;opacity:.85}} main{{padding:24px 40px;max-width:1280px}}
.cards{{display:flex;gap:14px;margin-bottom:10px}} .card{{background:#fff;border-radius:12px;padding:14px 22px;box-shadow:0 1px 3px #0002;min-width:120px}}
.card b{{display:block;font-size:28px}}
table{{width:100%;border-collapse:collapse;background:#fff;border-radius:12px;overflow:hidden;box-shadow:0 1px 3px #0002;margin-bottom:26px}}
th,td{{padding:9px 12px;border-bottom:1px solid #eef0f3;font-size:13.5px;text-align:left;vertical-align:top}} th{{background:#ecfdf5}}
.b{{color:#fff;border-radius:6px;padding:2px 8px;font-size:12px;font-weight:700;text-transform:uppercase}} .u{{word-break:break-all;color:#4b5563}}
a{{color:#047857}} footer{{padding:0 40px 30px;color:#6b7280;font-size:13px}}
</style></head><body>
<header><div class="ring"><span>{r.score}</span></div><div><h1>SEO audit: {escape(r.start_url)}</h1>
<p>{len(r.pages)} pages crawled · generated {escape(r.created_at)}</p></div></header>
<main><div class="cards"><div class="card"><b style="color:{SEV_COLOR['error']}">{c['error']}</b>Errors</div>
<div class="card"><b style="color:{SEV_COLOR['warning']}">{c['warning']}</b>Warnings</div>
<div class="card"><b style="color:{SEV_COLOR['notice']}">{c['notice']}</b>Notices</div>
<div class="card"><b>{len(r.pages)}</b>Pages</div></div>
<h2>Issues</h2><table><tr><th>Severity</th><th>Page</th><th>Issue</th><th>How to fix</th></tr>{issue_rows}</table>
<h2>Pages</h2><table><tr><th>URL</th><th>Status</th><th>Title</th><th>Words</th><th>Response</th><th>Score</th></tr>{''.join(page_rows)}</table>
</main><footer>Generated by SEO Site Audit Tool, built by Joseph Obaje.</footer></body></html>"""


def to_csv(r: AuditResult) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["severity", "url", "code", "message", "fix"])
    for i in r.issues:
        w.writerow([i.severity, i.url, i.code, i.message, i.fix])
    return buf.getvalue()


def save(r: AuditResult, path: str | Path) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    suffix = p.suffix.lower()
    if suffix in {".html", ".htm"}:
        p.write_text(to_html(r), encoding="utf-8")
    elif suffix == ".csv":
        p.write_text(to_csv(r), encoding="utf-8-sig")
    elif suffix == ".json":
        p.write_text(json.dumps(r.to_dict(), indent=2), encoding="utf-8")
    else:
        raise ValueError("Report must end in .html, .json or .csv")
    return p
